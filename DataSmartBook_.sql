SELECT
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE,
    CHARACTER_MAXIMUM_LENGTH,
    IS_NULLABLE,
    COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME IN (
    'customer_addresses',
    'orders',
    'order_items',
    'inventory'
)
ORDER BY TABLE_NAME, ORDINAL_POSITION;